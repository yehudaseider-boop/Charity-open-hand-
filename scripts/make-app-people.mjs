// Makes apps/mobile/src/components/people-art.ts from the website's unDraw people (src/components/illustration-art.ts),
// so the app and the For charities page share the same illustrations (30/10/2026). The website colours them with CSS
// variables; the app can't read those, so each variable becomes a token name that people.tsx fills in from
// apps/mobile/src/theme/tokens.ts. Only the pictures the app uses are copied, to keep the app small.
// Run: node scripts/make-app-people.mjs
import { readFileSync, writeFileSync } from "node:fs";

const PICK = ["loveIt", "dreamGift", "mobilePay", "workingTogether", "mailSent", "checklist"];
const TOKEN = { "--brand": "blue", "--brand-soft": "lightPurple", "--coral": "orange", "--honey": "lilac", "--honey-soft": "lilacSoft", "--navy": "navy" };

const src = readFileSync("src/components/illustration-art.ts", "utf8");
const body = src.slice(src.indexOf("{", src.indexOf("export const art")), src.lastIndexOf("} as const") + 1);
const art = JSON.parse(body.replace(/,\s*}$/, "}"));
const out = {};
for (const name of PICK) {
  if (!art[name]) throw new Error(`No picture called ${name}`);
  out[name] = art[name].replace(/var\((--[a-z-]+)\)/g, (_, v) => {
    if (!TOKEN[v]) throw new Error(`No app colour for ${v}`);
    return `{{${TOKEN[v]}}}`;
  });
}
const lines = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join("\n");
writeFileSync(
  "apps/mobile/src/components/people-art.ts",
  `// Generated by scripts/make-app-people.mjs from the website's src/components/illustration-art.ts: do not edit by hand.
// Illustrations from unDraw (undraw.co), MIT via undraw-svg: free for commercial use, not to be resold or collected
// into a competing library. Colours are token names ({{blue}} and so on), filled in by people.tsx.
export const peopleArt = {
${lines}
} as const;
export type PeopleName = keyof typeof peopleArt;
`,
);
console.log(`Wrote ${PICK.length} pictures`);
